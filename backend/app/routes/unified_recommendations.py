@router.get("/{subscription_id}/recommendations/summary")
async def get_recommendations_summary(
    subscription_id: str,
):
    """
    Get summary statistics about recommendations.
    
    Returns:
        {
            "subscriptionId": str,
            "total": int,
            "by_impact": {
                "High": int,
                "Medium": int,
                "Low": int
            },
            "by_category": {
                "HighAvailability": int,
                ...
            }
        }
    """
    try:
        # Load resilience evaluations
        data_path = get_subscription_dir(subscription_id)
        eval_file = data_path / "resilience_evaluations.json"
        
        if not path_exists(eval_file):
            raise HTTPException(
                status_code=404,
                detail=f"No recommendations found for subscription {subscription_id}"
            )
        
        data = read_json(eval_file, default={})
        
        # Extract failed checks as recommendations
        recommendations = []
        for resource_id, evaluation in data.get('evaluations', {}).items():
            for check in evaluation.get('checks', []):
                if check.get('status') == 'fail':
                    recommendations.append(check)
        
        # Build summary
        by_impact = {"High": 0, "Medium": 0, "Low": 0}
        by_category = {}
        
        for rec in recommendations:
            # Count by impact
            impact = rec.get('impact', 'Medium')
            by_impact[impact] = by_impact.get(impact, 0) + 1
            
            # Count by category
            category = rec.get('category', 'Other')
            by_category[category] = by_category.get(category, 0) + 1
        
        return {
            "subscriptionId": subscription_id,
            "total": len(recommendations),
            "by_impact": by_impact,
            "by_category": by_category,
            "generated": data.get('generated')
        }
        
    except FileNotFoundError:
        raise HTTPException(
            status_code=404,
            detail=f"No data found for subscription {subscription_id}"
        )
    except Exception as e:
        LOGGER.error(f"Error fetching summary: {e}", exc_info=True)
        raise HTTPException(
            status_code=500,
            detail=f"Error fetching summary: {str(e)}"
        )


