@router.get("/evaluate/{subscription_id}/summary")
def get_subscription_resilience_summary(subscription_id: str):
    """
    Get resilience summary for all resources (for frontend visualization).
    
    Returns per-resource pass/fail counts and pass percentage:
        {
            "/{subscription}/...resource1": {"total_checks": 10, "passed_checks": 7, "failed_checks": 3, "pass_percentage": 70},
            "/{subscription}/...resource2": {"total_checks": 5, "passed_checks": 5, "failed_checks": 0, "pass_percentage": 100},
            ...
        }
    """
    eval_path = get_resilience_evaluations_path(subscription_id)
    if not eval_path.exists():
        raise HTTPException(
            status_code=404,
            detail=f"Resilience evaluations not found for subscription {subscription_id}. "
                   f"Run evaluations first."
        )
    
    try:
        results = load_resilience_evaluations(subscription_id)
        evaluations = results.get("evaluations", {})
        
        summary = {}
        for resource_id, evaluation in evaluations.items():
            total = evaluation.get("total_checks", 0)
            passed = evaluation.get("passed_checks", 0)
            failed = evaluation.get("failed_checks", 0)
            pass_percentage = round((passed / total * 100) if total > 0 else 0, 1)
            
            summary[resource_id] = {
                "total_checks": total,
                "passed_checks": passed,
                "failed_checks": failed,
                "pass_percentage": pass_percentage,
            }
        
        return summary
    
    except Exception as e:
        LOGGER.error(f"Failed to get resilience summary for {subscription_id}: {e}")
        raise HTTPException(status_code=500, detail=str(e))


