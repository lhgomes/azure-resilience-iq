@router.post("/{subscription_id}/overrides")
def create_override(subscription_id: str, request: OverrideRequest):
    """
    Create or update a user override for a specific check.
    
    Body:
        - resource_id: Azure resource ID
        - recommendation_id: APRL recommendation GUID
        - new_status: "pass" or "fail"
        - user_identifier: Optional user identifier (default: "user")
    
    Returns:
        The created/updated override including check_uuid
    """
    if request.new_status not in ["pass", "fail"]:
        raise HTTPException(
            status_code=400,
            detail="new_status must be either 'pass' or 'fail'"
        )
    
    try:
        result = save_override(
            subscription_id=subscription_id,
            resource_id=request.resource_id,
            recommendation_id=request.recommendation_id,
            new_status=request.new_status,
            user_identifier=request.user_identifier
        )
        return result
    except Exception as e:
        LOGGER.error(f"Failed to save override for {subscription_id}: {e}")
        raise HTTPException(status_code=500, detail=str(e))


@router.delete("/{subscription_id}/overrides")
def remove_override(subscription_id: str, request: DeleteOverrideRequest):
    """
    Delete a user override.
    
    Body:
        - resilience_check_id: UUID of the check override to delete
    
    Returns:
        Success status
    """
    try:
        deleted = delete_override(subscription_id, request.resilience_check_id)
        if not deleted:
            raise HTTPException(
                status_code=404,
                detail=f"Override {request.resilience_check_id} not found"
            )
        return {"deleted": True, "resilience_check_id": request.resilience_check_id}
    except HTTPException:
        raise
    except Exception as e:
        LOGGER.error(f"Failed to delete override for {subscription_id}: {e}")
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/{subscription_id}/overrides/check")
def get_check_override(
    subscription_id: str,
    resource_id: str,
    recommendation_id: str
):
    """
    Get the override for a specific check if it exists.
    
    Query params:
        - resource_id: Azure resource ID
        - recommendation_id: APRL recommendation GUID
    
    Returns:
        Override data if exists, null otherwise
    """
    try:
        override = get_override_for_check(
            subscription_id=subscription_id,
            resource_id=resource_id,
            recommendation_id=recommendation_id
        )
        
        if override:
            check_uuid = generate_check_uuid(resource_id, recommendation_id)
            return {
                "check_uuid": check_uuid,
                **override
            }
        else:
            return None
    except Exception as e:
        LOGGER.error(f"Failed to get check override for {subscription_id}: {e}")
        raise HTTPException(status_code=500, detail=str(e))

